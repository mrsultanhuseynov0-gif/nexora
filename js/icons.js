  /**
   * Create SVG icon element
   * @param {string} name - Icon name
   * @param {object} options - Icon options
   * @returns {string} SVG HTML string
   */
  function create(name, options = {}) {
    const {
      size = 'md',
      className = '',
      strokeWidth = 2,
      fill = 'none',
      stroke = 'currentColor'
    } = options;

    const path = icons[name];
    if (!path) {
      console.warn(`NexoraIcons: Icon "${name}" not found`);
      return '';
    }

    const sizeClass = typeof size === 'string' && ['xs', 'sm', 'md', 'lg', 'xl', '2xl'].includes(size)
      ? `icon-${size}`
      : '';

    const customSize = typeof size === 'number' ? `width:${size}px;height:${size}px;` : '';

    return `<span class="icon ${sizeClass} ${className}" ${customSize ? `style="${customSize}"` : ''} aria-hidden="true">
      <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="${fill}" stroke="${stroke}" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round">
        ${path}
      </svg>
    </span>`;
  }

  /**
   * Render icon into DOM element
   * @param {HTMLElement|string} target - Element or selector
   * @param {string} name - Icon name
   * @param {object} options - Icon options
   */
  function render(target, name, options = {}) {
    const el = typeof target === 'string' ? document.querySelector(target) : target;
    if (!el) return;
    el.innerHTML = create(name, options);
  }

  /**
   * Replace all elements with data-icon attribute
   */
  function init() {
    document.querySelectorAll('[data-icon]').forEach(function (el) {
      const name = el.getAttribute('data-icon');
      const size = el.getAttribute('data-icon-size') || 'md';
      const className = el.getAttribute('data-icon-class') || '';
      el.innerHTML = create(name, { size, className }).replace(/^<span[^>]*>|<\/span>$/g, '');
      el.classList.add('icon');
      if (['xs', 'sm', 'md', 'lg', 'xl', '2xl'].includes(size)) {
        el.classList.add(`icon-${size}`);
      }
      if (className) {
        className.split(' ').forEach(function (c) {
          if (c) el.classList.add(c);
        });
      }
    });
  }

  /**
   * Get list of available icon names
   * @returns {string[]}
   */
  function getAvailableIcons() {
    return Object.keys(icons);
  }

